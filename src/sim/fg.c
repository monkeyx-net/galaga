/* An instruction: a place to go on from, and the vertical blank, which
   stops the foreground (z->pc where it goes on); IL also a jump's target */
#define I(n)                                                                                                           \
    case 0x##n:                                                                                                        \
    if (z->t >= z->budget) {                                                                                           \
        z->pc = 0x##n;                                                                                                 \
        return;                                                                                                        \
    }
#define IL(n)                                                                                                          \
    case 0x##n:                                                                                                        \
    x##n:                                                                                                              \
    if (z->t >= z->budget) {                                                                                           \
        z->pc = 0x##n;                                                                                                 \
        return;                                                                                                        \
    }

/* A write of the 06xx's control: the transfer main's NMI would make, at
   once, with the pointers and count in HL' (or DE' to read) and BC', and
   them as the NMIs leave them */
static void bus(Cpu *z, uint8_t ctrl)
{
    Io *io = z->g->io;
    uint16_t hl = (uint16_t)(z->h2 << 8 | z->l2), de = (uint16_t)(z->d2 << 8 | z->e2);
    int n = z->b2 << 8 | z->c2;
    if (!io) return;
    if (!(ctrl & 0x0F)) {
        io->ctrl = ctrl;
        return;
    }
    io_transfer(io, z->g, ctrl, ctrl & 0x10 ? de : hl, n);
    if (ctrl & 0x10) de = (uint16_t)(de + n);
    else hl = (uint16_t)(hl + n);
    z->h2 = (uint8_t)(hl >> 8), z->l2 = (uint8_t)hl;
    z->d2 = (uint8_t)(de >> 8), z->e2 = (uint8_t)de;
    z->b2 = z->c2 = 0;
}

